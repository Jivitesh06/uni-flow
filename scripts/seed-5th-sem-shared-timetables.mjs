/**
 * UniFlow — 5th Semester Shared Timetable Seeder & Publisher
 *
 * Usage:
 *   node scripts/seed-5th-sem-shared-timetables.mjs
 *
 * Optional with Firebase credentials to publish directly to Firestore:
 *   GOOGLE_APPLICATION_CREDENTIALS=./serviceAccountKey.json node scripts/seed-5th-sem-shared-timetables.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseChitkaraPdf } from '../src/lib/chitkaraTimetableParser.ts';
import {
  buildSharedGroupId,
  buildSharedGroupLabel,
  computeTimetableContentHash,
} from '../src/lib/sharedTimetable.ts';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

const PDF_FIXTURE_PATH = path.join(
  projectRoot,
  'tests',
  'fixtures',
  'Time Table-BE CSE 2024 batch-5th Semester-(wef 12.10.2026).pdf'
);

export async function generateSeededTimetables() {
  if (!fs.existsSync(PDF_FIXTURE_PATH)) {
    throw new Error(`PDF fixture not found at ${PDF_FIXTURE_PATH}`);
  }

  const pdfBuffer = fs.readFileSync(PDF_FIXTURE_PATH);
  const uint8 = new Uint8Array(pdfBuffer);
  const fixtureName = path.basename(PDF_FIXTURE_PATH);

  // Parse root to discover all sections
  const initial = await parseChitkaraPdf(uint8, undefined, fixtureName);
  const sectionsFound = initial.sectionsFound || [];

  if (sectionsFound.length === 0) {
    throw new Error('No sections found in the timetable PDF fixture.');
  }

  const seededDocs = {};

  for (const fullSec of sectionsFound) {
    // Extract section letter, e.g. "BE-CSE-5A" -> "A"
    const secLetter = fullSec.replace(/^BE-CSE-5/i, '').toUpperCase();
    const parsed = await parseChitkaraPdf(uint8, fullSec, fixtureName);

    const groupParams = {
      institution: 'Chitkara University',
      program: 'BE-CSE',
      batch: '2024',
      semester: 5,
      section: secLetter,
    };

    const groupId = buildSharedGroupId(groupParams);
    const groupLabel = buildSharedGroupLabel(groupParams);

    const slots = parsed.lectures.map((l, idx) => ({
      id: `seed_${secLetter.toLowerCase()}_${idx + 1}`,
      subjectCode: l.subjectCode,
      subjectName: l.subjectName,
      faculty: l.faculty,
      room: l.room,
      dayOfWeek: l.dayOfWeek,
      startTime: l.startTime,
      endTime: l.endTime,
      color: l.color,
      group: l.group || 'ALL',
      requiresReview: l.requiresReview || false,
    }));

    const contentHash = computeTimetableContentHash(
      slots,
      parsed.effectiveDate || '12-10-2026'
    );

    seededDocs[groupId] = {
      id: groupId,
      groupLabel,
      institution: 'Chitkara University',
      program: 'BE-CSE',
      batch: '2024',
      semester: 5,
      section: fullSec,
      version: 1,
      effectiveDate: parsed.effectiveDate || '12-10-2026',
      contentHash,
      slots,
      publishedAt: null,
      publishedBy: 'system-seed',
      publishedByName: 'CSED Department Office',
      publisherRole: 'publisher',
      updatedAt: null,
      createdAt: null,
    };
  }

  return { seededDocs, sectionsFound, effectiveDate: initial.effectiveDate || '12-10-2026' };
}

async function main() {
  console.log('\n===============================================================');
  console.log(' UniFlow: 5th-Semester Shared Timetable Seeder & Publisher');
  console.log('===============================================================\n');

  console.log(`Parsing real fixture: ${path.basename(PDF_FIXTURE_PATH)}...`);
  const { seededDocs, sectionsFound, effectiveDate } = await generateSeededTimetables();

  console.log(`✓ Discovered ${sectionsFound.length} sections: ${sectionsFound.join(', ')}`);
  console.log(`✓ Effective date: ${effectiveDate}`);

  // Write TypeScript dataset file for frontend bundle fallback
  const tsContent = `/**
 * Pre-seeded 5th-Semester Departmental Timetables
 * Auto-generated by scripts/seed-5th-sem-shared-timetables.mjs
 * Source: ${path.basename(PDF_FIXTURE_PATH)}
 * Effective Date: ${effectiveDate}
 * 
 * Provides 0ms instant timetable display upon student registration without requiring
 * Google Cloud Console setup, Gmail OAuth, or manual PDF upload.
 */

import type { SharedTimetableDoc } from '../lib/sharedTimetable.ts';

export const SEEDED_5TH_SEM_TIMETABLES: Record<string, SharedTimetableDoc> = ${JSON.stringify(
    seededDocs,
    null,
    2
  )};
`;

  const tsFilePath = path.join(projectRoot, 'src', 'data', 'seededSharedTimetables.ts');
  const jsonFilePath = path.join(projectRoot, 'src', 'data', 'seededSharedTimetables.json');

  fs.mkdirSync(path.dirname(tsFilePath), { recursive: true });
  fs.writeFileSync(tsFilePath, tsContent, 'utf-8');
  fs.writeFileSync(jsonFilePath, JSON.stringify(seededDocs, null, 2), 'utf-8');

  console.log(`✓ Wrote client dataset to ${path.relative(projectRoot, tsFilePath)}`);
  console.log(`✓ Wrote JSON dataset to ${path.relative(projectRoot, jsonFilePath)}`);

  for (const [id, doc] of Object.entries(seededDocs)) {
    console.log(`  - Section ${doc.section}: ${doc.slots.length} slots | ID: ${id} | Hash: ${doc.contentHash}`);
  }

  // Attempt Firestore publication if credentials or emulator are configured
  const serviceAccountKey =
    process.env.GOOGLE_APPLICATION_CREDENTIALS || process.env.FIREBASE_SERVICE_ACCOUNT;
  const isEmulator = Boolean(process.env.FIRESTORE_EMULATOR_HOST);

  if (serviceAccountKey || isEmulator) {
    try {
      console.log('\nAttempting live Firestore publication...');
      const admin = await import('firebase-admin');
      if (admin.default.apps.length === 0) {
        if (serviceAccountKey && fs.existsSync(serviceAccountKey)) {
          const serviceAccount = JSON.parse(fs.readFileSync(serviceAccountKey, 'utf-8'));
          admin.default.initializeApp({
            credential: admin.default.credential.cert(serviceAccount),
          });
        } else {
          admin.default.initializeApp();
        }
      }

      const db = admin.default.firestore();
      let written = 0;
      let duplicates = 0;

      for (const [groupId, data] of Object.entries(seededDocs)) {
        const docRef = db.collection('sharedTimetables').doc(groupId);
        const existing = await docRef.get();

        if (existing.exists && existing.data().contentHash === data.contentHash) {
          console.log(`  [SKIP DUPLICATE] ${groupId} already published (Hash matched).`);
          duplicates++;
          continue;
        }

        await docRef.set(
          {
            ...data,
            publishedAt: admin.default.firestore.FieldValue.serverTimestamp(),
            updatedAt: admin.default.firestore.FieldValue.serverTimestamp(),
            createdAt: existing.exists
              ? existing.data().createdAt
              : admin.default.firestore.FieldValue.serverTimestamp(),
          },
          { merge: true }
        );
        console.log(`  [PUBLISHED] ${groupId} successfully written to Firestore.`);
        written++;
      }

      console.log(`\nFirestore Publication Summary: ${written} written, ${duplicates} up-to-date duplicates.`);
    } catch (err) {
      console.warn('\nFirestore publication note (Admin SDK not connected):', err.message);
    }
  } else {
    console.log('\n---------------------------------------------------------------');
    console.log(' Firestore Live Publication Status: PREPARED (Idempotent)');
    console.log(' Client-side instant shared timetable fallback is ready and active.');
    console.log(' To publish directly to cloud Firestore using Admin SDK credentials, run:');
    console.log('   GOOGLE_APPLICATION_CREDENTIALS=path/to/key.json node scripts/seed-5th-sem-shared-timetables.mjs');
    console.log('---------------------------------------------------------------\n');
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error('Seeding failed:', err);
    process.exit(1);
  });
}
