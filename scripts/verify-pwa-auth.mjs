import fs from 'fs';
import path from 'path';

console.log('=== Running UniFlow PWA & Auth Verification Suite ===\n');

let passCount = 0;
let failCount = 0;

function assert(condition, message) {
  if (condition) {
    console.log(`[PASS] ${message}`);
    passCount++;
  } else {
    console.error(`[FAIL] ${message}`);
    failCount++;
  }
}

// 1. Verify Manifest
const manifestPath = path.resolve('dist/manifest.webmanifest');
assert(fs.existsSync(manifestPath), 'dist/manifest.webmanifest exists');
if (fs.existsSync(manifestPath)) {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  assert(manifest.name === 'UniFlow', `Manifest name is "UniFlow" (actual: "${manifest.name}")`);
  assert(manifest.short_name === 'UniFlow', `Manifest short_name is "UniFlow" (actual: "${manifest.short_name}")`);
  assert(manifest.description === 'Your College Life, In Sync.', `Manifest description matches (actual: "${manifest.description}")`);
  assert(manifest.display === 'standalone', `Manifest display is "standalone" (actual: "${manifest.display}")`);
  assert(manifest.start_url === '/', `Manifest start_url is "/" (actual: "${manifest.start_url}")`);
  assert(manifest.theme_color === '#2563eb', `Manifest theme_color is "#2563eb" (actual: "${manifest.theme_color}")`);
  assert(manifest.background_color === '#ffffff', `Manifest background_color is "#ffffff" (actual: "${manifest.background_color}")`);
  assert(Array.isArray(manifest.icons) && manifest.icons.length >= 2, `Manifest has at least 2 icons (count: ${manifest.icons?.length})`);

  const has192 = manifest.icons.some(i => i.sizes === '192x192' && i.type === 'image/png');
  const has512 = manifest.icons.some(i => i.sizes === '512x512' && i.type === 'image/png');
  assert(has192, 'Manifest includes 192x192 PNG icon');
  assert(has512, 'Manifest includes 512x512 PNG icon');
}

// 2. Verify Physical Icon Files
const icon192Path = path.resolve('public/icons/icon-192x192.png');
const icon512Path = path.resolve('public/icons/icon-512x512.png');
const iconApplePath = path.resolve('public/icons/apple-touch-icon.png');
const iconMaskablePath = path.resolve('public/icons/icon-512x512-maskable.png');

assert(fs.existsSync(icon192Path), 'public/icons/icon-192x192.png exists');
assert(fs.existsSync(icon512Path), 'public/icons/icon-512x512.png exists');
assert(fs.existsSync(iconApplePath), 'public/icons/apple-touch-icon.png exists');
assert(fs.existsSync(iconMaskablePath), 'public/icons/icon-512x512-maskable.png exists');

// Verify PNG magic bytes [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]
if (fs.existsSync(icon192Path)) {
  const buf = fs.readFileSync(icon192Path);
  const isPng = buf[0] === 0x89 && buf[1] === 0x50 && buf[2] === 0x4E && buf[3] === 0x47;
  assert(isPng, '192x192 icon contains valid PNG binary signature');
}

// 3. Verify Service Worker & Caching Security
const swPath = path.resolve('dist/sw.js');
assert(fs.existsSync(swPath), 'dist/sw.js generated by workbox');
if (fs.existsSync(swPath)) {
  const swContent = fs.readFileSync(swPath, 'utf8');
  assert(swContent.includes('identitytoolkit'), 'SW denylist blocks identitytoolkit (Firebase Auth API)');
  assert(swContent.includes('firestore'), 'SW denylist blocks firestore.googleapis.com (no private data cached)');
  assert(swContent.includes('securetoken'), 'SW denylist blocks securetoken.googleapis.com (no tokens in SW cache)');
  assert(swContent.includes('precacheAndRoute'), 'SW utilizes workbox precacheAndRoute for static app shell');
}

// 4. Verify Firebase Auth Persistence Setup
const firebaseSrc = fs.readFileSync(path.resolve('src/lib/firebase.ts'), 'utf8');
assert(firebaseSrc.includes('browserLocalPersistence'), 'src/lib/firebase.ts imports and uses browserLocalPersistence');
assert(firebaseSrc.includes('setPersistence'), 'src/lib/firebase.ts configures setPersistence');
assert(firebaseSrc.includes('ensureAuthPersistence'), 'src/lib/firebase.ts exports ensureAuthPersistence helper');

const authContextSrc = fs.readFileSync(path.resolve('src/contexts/AuthContext.tsx'), 'utf8');
assert(authContextSrc.includes('ensureAuthPersistence()'), 'AuthContext calls ensureAuthPersistence before sign-in flows');
assert(authContextSrc.includes('onAuthStateChanged'), 'AuthContext uses onAuthStateChanged as centralized single listener');
assert(authContextSrc.includes('fallbackProfile'), 'AuthContext handles offline user profile restoration safely');

// 5. Verify ProtectedRoute loading behavior
const protectedRouteSrc = fs.readFileSync(path.resolve('src/components/auth/ProtectedRoute.tsx'), 'utf8');
assert(protectedRouteSrc.includes('if (loading)'), 'ProtectedRoute holds render until auth loading completes');

// 6. Verify iOS Safari Install instructions
const iosModalSrc = fs.readFileSync(path.resolve('src/components/pwa/IOSInstallModal.tsx'), 'utf8');
assert(iosModalSrc.includes('Share') && iosModalSrc.includes('Add to Home Screen'), 'IOSInstallModal provides Share -> Add to Home Screen instructions');

console.log(`\nVerification Complete: ${passCount} Passed, ${failCount} Failed.`);
if (failCount > 0) process.exit(1);
